import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const contentDir = join(root, 'src/content')
const wordsPerMinute = 220

function countWords(source) {
  const body = source.replace(/^---\r?\n[\s\S]*?\r?\n---/, ' ')
  return body.split(/\s+/).filter((word) => /[A-Za-z0-9]/.test(word)).length
}

const entries = readdirSync(contentDir)
  .filter((file) => file.endsWith('.mdx'))
  .sort((a, b) => a.localeCompare(b, 'en'))
  .map((file) => {
    const slug = file.slice(0, -4)
    const source = readFileSync(join(contentDir, file), 'utf8')
    const minutes = Math.max(1, Math.round(countWords(source) / wordsPerMinute))
    return `  '${slug}': ${minutes},`
  })

const output = `// Generated by scripts/generate-reading-minutes.mjs. Do not edit by hand.
export const readingMinutesBySlug: Record<string, number> = {
${entries.join('\n')}
}
`

const destination = join(root, 'src/generated')
mkdirSync(destination, { recursive: true })
writeFileSync(join(destination, 'readingMinutes.ts'), output)
